<script>
  const track = document.getElementById("sliderTrack");
  let index = 0;

  // Clone slides to simulate infinite loop
  const slides = Array.from(track.children);
  const visibleSlides = 3; // Number of original visible slides to clone
  slides.slice(0, visibleSlides).forEach(slide => {
    const clone = slide.cloneNode(true);
    track.appendChild(clone);
  });

  function getSlideWidth() {
    const slide = document.querySelector(".slide");
    return slide ? slide.offsetWidth + 24 : 0; // includes the gap
  }

  function moveSlider() {
    const slideWidth = getSlideWidth();
    index++;
    track.style.transform = `translateX(-${slideWidth * index}px)`;

    if (index >= slides.length) {
      setTimeout(() => {
        track.style.transition = "none";
        index = 0;
        track.style.transform = `translateX(0px)`;
        setTimeout(() => {
          track.style.transition = "transform 0.5s ease-in-out";
        }, 50);
      }, 500);
    }
  }

  let sliderInterval = setInterval(moveSlider, 2000);

  // Pause on hover
  track.addEventListener("mouseenter", () => clearInterval(sliderInterval));
  track.addEventListener("mouseleave", () => {
    sliderInterval = setInterval(moveSlider, 2000);
  });
</script>

        
