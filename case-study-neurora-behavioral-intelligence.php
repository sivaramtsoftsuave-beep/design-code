        <script>
        $(document).ready(function() {
            // Auto-discovers every #sectionN link/target pair under the TOC,
            // so adding a new section later needs no changes here.
            var sections = [];
            $('.border-line .nav-item > a.nav-link').each(function() {
                var $link = $(this);
                var href = ($link.attr('href') || '').trim();
                var id = href.indexOf('#') === 0 ? href.slice(1) : '';
                var el = id ? document.getElementById(id) : null;
                if (el) {
                    sections.push({ $link: $link, el: el });
                }
            });
            if (!sections.length) return;

            function fixedHeaderHeight() {
                var $header = $('.navigation').first();
                return $header.length ? $header.outerHeight() : 0;
            }

            function highlightActiveSection() {
                // Trigger line sits just below the fixed header, then a fifth
                // of the viewport height further down, so a section only
                // takes over once it's genuinely in view. Using the viewport
                // height (not a flat pixel value) keeps this correct across
                // phone / tablet / desktop / large-desktop screens, and it's
                // a deterministic "furthest section reached" pick, so it can
                // never go backward or land on no highlight at all.
                var triggerLine = window.scrollY + fixedHeaderHeight() + ($(window).height() * 0.2);
                var current = sections[0];
                sections.forEach(function(section) {
                    var top = section.el.getBoundingClientRect().top + window.scrollY;
                    if (top <= triggerLine) {
                        current = section;
                    }
                });
                sections.forEach(function(section) {
                    section.$link.toggleClass('active', section === current);
                });
            }

            var rafPending = false;
            function onScrollOrResize() {
                if (rafPending) return;
                rafPending = true;
                requestAnimationFrame(function() {
                    rafPending = false;
                    highlightActiveSection();
                });
            }

            $(window).on('scroll resize', onScrollOrResize);
            highlightActiveSection();
        });
        </script>

        <script>
        $(document).ready(function() {
            // Animates each analytics circle from 0% up to its data-percent
            // once it scrolls into view (fires only once per circle).
            var circles = document.querySelectorAll('.circle-chart[data-percent]');
            if (!circles.length) return;

            function animateCircle(el) {
                var target = parseFloat(el.getAttribute('data-percent')) || 0;
                var valueEl = el.querySelector('.circle-value');
                var duration = 1200;
                var start = null;

                function step(timestamp) {
                    if (start === null) start = timestamp;
                    var progress = Math.min((timestamp - start) / duration, 1);
                    var eased = 1 - Math.pow(1 - progress, 3);
                    var current = target * eased;
                    el.style.setProperty('--percent', current);
                    if (valueEl) valueEl.textContent = Math.round(current) + '%';
                    if (progress < 1) {
                        requestAnimationFrame(step);
                    } else {
                        el.style.setProperty('--percent', target);
                        if (valueEl) valueEl.textContent = target + '%';
                    }
                }
                requestAnimationFrame(step);
            }

            var circleObserver = new IntersectionObserver(function(entries) {
                entries.forEach(function(entry) {
                    if (entry.isIntersecting) {
                        animateCircle(entry.target);
                        circleObserver.unobserve(entry.target);
                    }
                });
            }, { threshold: 0.4 });

            circles.forEach(function(el) { circleObserver.observe(el); });
        });
        </script>
